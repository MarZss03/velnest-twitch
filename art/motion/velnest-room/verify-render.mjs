import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {stat,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
const output=fileURLToPath(new URL('./renders/velnest-room.mp4',import.meta.url));
const exe=name=>process.platform==='win32'?`${name}.exe`:name;
const probe=JSON.parse(execFileSync(exe('ffprobe'),['-v','error','-count_frames','-show_streams','-show_format','-of','json',output],{encoding:'utf8'}));
const video=probe.streams.find(stream=>stream.codec_type==='video');
assert.equal(video.width,1920); assert.equal(video.height,1080);
assert.equal(video.avg_frame_rate,'30/1'); assert.equal(Number(video.nb_read_frames),360);
assert.ok(Math.abs(Number(probe.format.duration)-12)<.04);
assert.equal(probe.streams.filter(stream=>stream.codec_type==='audio').length,0,'This delivery is intentionally silent');
const sampled=execFileSync(exe('ffmpeg'),['-v','error','-i',output,'-vf','fps=1','-f','framemd5','-'],{encoding:'utf8'});
const hashes=sampled.split('\n').filter(line=>line && !line.startsWith('#')).map(line=>line.split(',').at(-1).trim());
const unique=new Set(hashes).size;
assert.equal(hashes.length,12);
assert.ok(unique>=10,'The actual decoded video must change throughout the character/camera sequence');
const result={passed:true,width:video.width,height:video.height,fps:30,frames:Number(video.nb_read_frames),duration:Number(probe.format.duration),codec:video.codec_name,pixelFormat:video.pix_fmt,audioStreams:0,bytes:(await stat(output)).size,decodedSamples:hashes.length,uniqueSampleFrames:unique};
await writeFile(new URL('./render-verification.json',import.meta.url),`${JSON.stringify(result,null,2)}\n`);
console.log(JSON.stringify(result));
